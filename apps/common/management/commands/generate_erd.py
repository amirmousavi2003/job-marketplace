from django.apps import apps
from django.core.management.base import BaseCommand
from django.db import models

LOCAL_PREFIX = "apps."


def _local_models():
    return sorted(
        (m for m in apps.get_models() if m.__module__.startswith(LOCAL_PREFIX)),
        key=lambda m: (m._meta.app_label, m.__name__),
    )


class Command(BaseCommand):
    help = (
        "Print the database design (ERD, deletion rules, constraints) as Markdown, from the models."
    )

    def handle(self, *args, **options):
        local = _local_models()
        out = [
            "# Database design (generated)",
            "",
            "Generated by `python manage.py generate_erd`. Do not edit by hand.",
            "",
            "## Entity relationship diagram",
            "",
            "```mermaid",
            "erDiagram",
        ]
        relations, fk_rows, constraint_rows = [], [], []
        for model in local:
            out.append(f"  {model.__name__} {{")
            out.append("    bigint id PK")
            for field in model._meta.get_fields():
                if not getattr(field, "concrete", False) or field.primary_key:
                    continue
                if isinstance(field, models.ForeignKey | models.OneToOneField):
                    out.append(f"    bigint {field.name}_id FK")
                elif field.unique or field.choices:
                    unique = " UK" if field.unique else ""
                    out.append(f"    {field.get_internal_type().lower()} {field.name}{unique}")
            out.append("  }")
            for field in model._meta.get_fields():
                if isinstance(field, models.ForeignKey | models.OneToOneField) and field.concrete:
                    target = field.related_model
                    if (
                        target.__module__.startswith(LOCAL_PREFIX)
                        or target._meta.label == "accounts.User"
                    ):
                        one = isinstance(field, models.OneToOneField)
                        card = "||--o|" if one else ("|o--o{" if field.null else "||--o{")
                        relations.append(
                            f'  {target.__name__} {card} {model.__name__} : "{field.name}"'
                        )
                    nullable = "yes" if field.null else "no"
                    fk_rows.append(
                        f"| `{model.__name__}.{field.name}` | {target.__name__} | "
                        f"{field.remote_field.on_delete.__name__} | {nullable} |"
                    )
            for c in model._meta.constraints:
                kind = type(c).__name__.replace("Constraint", "")
                extra = (
                    " (partial)"
                    if getattr(c, "condition", None) is not None and kind == "Unique"
                    else ""
                )
                constraint_rows.append(f"| `{model.__name__}` | `{c.name}` | {kind}{extra} |")
        out += sorted(set(relations)) + ["```", ""]
        out += [
            "## Deletion rules (what happens when the parent row is deleted)",
            "",
            "PROTECT = deletion is refused while children exist. CASCADE = children are deleted. "
            "SET_NULL = the link is cleared.",
            "",
            "| Foreign key | Parent | on_delete | nullable |",
            "|---|---|---|---|",
        ]
        out += sorted(set(fk_rows)) + [""]
        out += (
            [
                "## Database constraints",
                "",
                "Rules the database enforces itself, whatever the application does.",
                "",
                "| Model | Constraint | Kind |",
                "|---|---|---|",
            ]
            + sorted(set(constraint_rows))
            + [""]
        )
        out += [
            "Not expressible in Django and added in migrations as SQL: composite foreign keys "
            "`(job_post_id, post_type)` from `EmploymentDetail`, `ProjectDetail`, "
            "`Application` and "
            "`ProjectProposal` to `JobPost(id, post_type)`.",
            "",
        ]
        self.stdout.write("\n".join(out))
